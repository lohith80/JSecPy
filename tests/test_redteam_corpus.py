"""Adversarial red-team corpus.

43 Java cases generated by a red-team pass against JSecPy, split into:

* ``detect``    - the named rule MUST fire (recall contract).
* ``clean``     - NO rule may fire (precision / anti-false-positive contract).
* ``known-gap`` - a documented limitation of the intra-procedural model
                  (taint through maps/collections, cross-method flow,
                  field storage, Random subclassing). Tracked as xfail so it
                  stays visible and flips to xpass the day we close it.

Labels here are reconciled with the ACTUAL engine, not the red-team's guesses:
a few cases the red-team predicted as gaps are in fact detected (the crypto and
TLS rules are stronger than the documented model), and are labelled ``detect``.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from jsecpy.config import Config
from jsecpy.engine import Engine
from jsecpy.model import Severity

CORPUS = json.loads(
    (Path(__file__).parent / "corpus" / "redteam.json").read_text(encoding="utf-8")
)["cases"]

# Red-team predicted these as known gaps, but the real rules detect them.
_RECLASSIFY_TO_DETECT = {
    "Md5LowercaseDigest.java",   # WeakHash is case-insensitive
    "MixedCaseDesEcbCipher.java",  # WeakCipher upper-cases the transformation
    "LaxHostnameVerifier.java",  # TLS rule flags the always-true verifier
}


def _label(case: dict) -> str:
    if case["filename"] in _RECLASSIFY_TO_DETECT:
        return "detect"
    return case["expect"]


def _scan(case: dict):
    engine = Engine(Config(min_severity=Severity.INFO))
    findings = engine.scan_source(case["filename"], case["java"])
    return {f.rule_id for f in findings}


_DETECT = [c for c in CORPUS if _label(c) == "detect"]
_CLEAN = [c for c in CORPUS if _label(c) == "clean"]
_GAP = [c for c in CORPUS if _label(c) == "known-gap"]


@pytest.mark.parametrize("case", _DETECT, ids=[c["filename"] for c in _DETECT])
def test_detect(case):
    fired = _scan(case)
    assert case["rule_id"] in fired, (
        f"{case['filename']}: expected {case['rule_id']} to fire, got {sorted(fired)}\n"
        f"rationale: {case['rationale']}"
    )


@pytest.mark.parametrize("case", _CLEAN, ids=[c["filename"] for c in _CLEAN])
def test_clean(case):
    fired = _scan(case)
    assert not fired, f"{case['filename']}: false positive(s) {sorted(fired)}"


@pytest.mark.parametrize("case", _GAP, ids=[c["filename"] for c in _GAP])
@pytest.mark.xfail(reason="documented intra-procedural limitation", strict=True)
def test_known_gap(case):
    fired = _scan(case)
    assert case["rule_id"] in fired


def test_corpus_is_substantial():
    assert len(_DETECT) >= 24
    assert len(_CLEAN) >= 14
    assert len(CORPUS) == len(_DETECT) + len(_CLEAN) + len(_GAP)
